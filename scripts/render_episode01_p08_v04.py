def filled_gradient(size,top,bottom):
  w,h=size
  arr=np.empty((h,w,3),np.uint8)
  for y in range(h):
    v=y/max(1,h-1);arr[y,:,:]=np.array(top)*(1-v)+np.array(bottom)*v
  return Image.fromarray(arr)

def cover(image,region,amount=(50,65,72),strength=0.75):
  mask=Image.new('L',image.size,0);m=ImageDraw.Draw(mask);m.rectangle(region,fill=int(255*strength));mask=mask.filter(ImageFilter.GaussianBlur(26));fog=Image.new('RGB',image.size,amount);return Image.composite(fog,image,mask)

def tile_crop(src,rect,target):
  crop=src.crop(rect)
  ratio=max(target[0]/crop.width,target[1]/crop.height)
  crop=crop.resize((int(crop.width*ratio),int(crop.height*ratio)),Image.Resampling.LANCZOS)
  dx=(crop.width-target[0])//2;dy=(crop.height-target[1])//2
  return crop.crop((dx,dy,dx+target[0],dy+target[1]))

def paste_with_fade(dst,clip,xy,fade=28,opacity=255):
  x,y=xy;w,h=clip.size
  mask=Image.new('L',(w,h),0)
  # Use tapered boundaries, with an opaque core and organic blending.
  p=np.zeros((h,w),dtype=np.uint8)
  xfade=np.minimum(np.arange(w),np.arange(w)[::-1])/max(1,fade)
  yfade=np.minimum(np.arange(h),np.arange(h)[::-1])/max(1,fade)
  p[:,:]=np.clip(np.minimum(xfade[None,:],yfade[:,None])*255,0,opacity)
  mask=Image.fromarray(p,'L')
  dst.paste(clip,(x,y),mask)

def polygon_bubble(box,lines,size=31,tail=None,align='center',line_gap=8,radius=35):
  x0,y0,x1,y1=box
  d=ImageDraw.Draw(page)
  d.rounded_rectangle(box,radius=radius,fill=warmwhite,outline=ink,width=4)
  if tail:
    tx,ty=tail
    base=(min(x1-35,max(x0+35,tx)), y1-2) if ty>y1 else (min(x1-35,max(x0+35,tx)),y0+2)
    pts=[(base[0]-13,base[1]),(base[0]+16,base[1]),(tx,ty)]
    d.polygon(pts, fill=warmwhite)
    d.line([pts[0],pts[2],pts[1]],fill=ink,width=3,joint='curve')
  font=ImageFont.truetype(FONT,size)
  linesp=size+line_gap
  tops=y0+((y1-y0)-len(lines)*linesp+line_gap)//2
  for i,line in enumerate(lines):
    left,top,right,bottom=d.textbbox((0,0),line,font=font)
    textw=right-left
    xx=x0+(x1-x0-textw)//2 if align=='center' else x0+25
    yy=tops+i*linesp
    d.text((xx,yy),line,fill=ink,font=font,stroke_width=0)
  # Important: unlike text generated by imagegen, every text is scripted.

