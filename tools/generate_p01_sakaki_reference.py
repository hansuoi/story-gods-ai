#!/usr/bin/env python3
"""P01コマ3のカラー構図検証素材。正式な完成原稿ではない。"""
from pathlib import Path
import hashlib, math, random
from PIL import Image, ImageDraw

def generate(path):
    r = random.Random(241018)
    im = Image.new("RGB", (1400, 720), "#102c43")
    d = ImageDraw.Draw(im)
    def p(points, color, edge="#10212e", width=4):
        d.polygon(points, fill=color)
        if edge: d.line(points+[points[0]], fill=edge, width=width, joint="curve")
    # 水没した地下通路、閉じた扉、奥の救助員
    p([(0,0),(1400,0),(950,280),(0,190)], "#0a1d31")
    for i in range(10):
        x=920+i*52
        d.line([(x,0),(930+(x-930)*.14,270)],fill="#45637b",width=2)
    p([(1110,90),(1320,80),(1320,445),(1110,390)], "#455a66")
    for i in range(4):
        y=120+i*75
        d.line([(1117,y),(1315,y)],fill="#839ca0",width=3)
    p([(1030,245),(1100,210),(1150,255),(1160,370),(1035,370)], "#a95739")
    p([(1064,220),(1080,184),(1133,176),(1158,205),(1140,226)], "#d2d5c7")
    d.line([(1127,277),(1200,280),(1220,260)],fill="#b87445",width=25)
    p([(0,415),(1400,410),(1400,720),(0,720)], "#16435b")
    for i in range(90):
        x=r.randrange(1400); y=r.randrange(425,720)
        d.line([(x,y),(min(1400,x+r.randrange(15,115)),y)],fill=r.choice(["#3a7692","#70a7b3","#255f7c"]),width=r.choice([1,2,3]))
    # 神谷榊。顔を出さず、白シャツ・黒ズボン・革靴で踏み込む。
    p([(235,-20),(560,-20),(666,110),(630,270),(565,344),(340,338),(205,110)], "#071927")
    p([(255,40),(217,84),(205,254),(260,298),(308,262),(324,105)], "#b7ccd0")
    p([(216,210),(302,224),(298,261),(228,267)], "#edf0dd")
    p([(550,20),(615,69),(665,160),(656,246),(611,283),(570,253)], "#d5e2df")
    p([(591,218),(656,211),(656,246),(605,270)], "#f3f0df")
    p([(320,-24),(540,-24),(580,85),(571,208),(550,307),(475,334),(350,318),(307,220),(300,110)], "#e2ece8")
    p([(320,15),(352,80),(370,220),(407,295),(355,283)], "#b1c7d0",None)
    p([(500,0),(560,68),(556,205),(520,287),(484,303)], "#f6f2d8",None)
    p([(345,300),(475,317),(550,292),(548,342),(468,359),(365,342)], "#29394a")
    d.line([(365,325),(475,345),(538,320)],fill="#778f9a",width=7)
    p([(610,266),(655,250),(674,285),(657,328),(621,326)], "#b78d75")
    p([(230,263),(280,265),(290,309),(263,327),(232,306)], "#b78d75")
    p([(366,342),(470,356),(460,475),(435,560),(361,558),(344,481)], "#26384b")
    p([(474,352),(555,339),(614,438),(679,540),(615,580),(535,512),(470,440)], "#26384b")
    d.line([(370,389),(400,469),(380,525)],fill="#617f90",width=5)
    d.line([(524,399),(578,465),(633,535)],fill="#617f90",width=5)
    p([(360,526),(427,528),(448,561),(446,601),(344,608),(322,587),(330,558)], "#111e2c")
    p([(338,562),(413,543),(430,560),(415,574),(339,585)], "#526777",None)
    p([(603,516),(665,506),(731,536),(775,563),(789,607),(775,643),(646,648),(587,619),(578,578)], "#101e2b")
    p([(620,527),(676,515),(736,553),(765,586),(745,596),(673,579)], "#536c7d",None)
    d.line([(608,611),(659,631),(771,628)],fill="#95acb5",width=5)
    for i in range(4):
        d.line([(636+i*13,548),(648+i*12,557)],fill="#a8b6b7",width=2)
    # 足元の水しぶき
    for cx,cy,rad in [(775,624,52),(618,635,41),(369,597,36)]:
        for i in range(45):
            a=r.random()*math.tau
            x=cx+math.cos(a)*rad*r.uniform(.5,1.6)
            y=cy+math.sin(a)*rad*.4*r.uniform(.5,1.6)
            if 0<x<1400 and 410<y<720:
                d.line([(x,y),(x+math.cos(a)*12,y-math.sin(a)*12)],fill=r.choice(["#b3e2e9","#77c7d9","#dcf3f1"]),width=2)
    for i in range(300):
        x=r.randrange(1400); y=r.randrange(720)
        d.line([(x,y),(x-3,y+r.randrange(9,33))],fill=r.choice(["#4e849b","#6e9eae","#a1c6cf"]),width=1)
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    im.save(path,optimize=True)
    return hashlib.sha256(path.read_bytes()).hexdigest()

if __name__ == "__main__":
    path="docs/art/episode-01/finish/final-candidates/p01/assets/sakaki-entrance-reference-v01.png"
